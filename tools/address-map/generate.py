#!/usr/bin/env python3
"""Generate the selected ECI address arithmetic; never allocates domain codes."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def render(root=ROOT):
    cfg = json.loads((root / 'model/data/selected-8k.json').read_text())[0]['configuration']
    basis = cfg['domain_encoding']['kernel_basis_bytes']
    bases = [w['base_bytes'] for w in cfg['workers']]
    assert cfg['usable_address_bits'] == 38
    assert cfg['block_stride_bytes'] == 8192
    assert len(basis) == 19 and len(bases) == 7
    assert cfg['domain_encoding']['prefix_indices'] is None
    # Triangular basis permits direct extraction of each domain bit. Validate
    # that no other basis vector or worker base contributes to that pivot.
    pivots = [v.bit_length() - 1 for v in basis]
    assert len(set(pivots)) == len(pivots)
    for i, pivot in enumerate(pivots):
        assert all(not (v >> pivot & 1) for j, v in enumerate(basis) if i != j)
        assert all(not (b >> pivot & 1) for b in bases)
    constants = dict(address_bits=38, block_bytes=8192, line_bytes=128,
                     domain_bits=19, domain_limit=1 << 19, max_workers=7,
                     default_workers=4, default_slots=16)
    for direction in ('rx', 'tx'):
        desc = cfg['directions'][direction]
        ctrl = desc['control_offsets_bytes']
        overflow = desc['overflow_offsets_bytes']
        assert ctrl[1] == ctrl[0] + 128
        assert overflow == list(range(ctrl[0] + 256, ctrl[0] + 256 + 12 * 128, 128))
        constants[direction + '_control'] = ctrl[0]
        constants[direction + '_overflow'] = overflow[0]
    constants['overflow_lines'] = 12
    preamble = 'Generated by tools/address-map/generate.py from model/data/selected-8k.json. Do not edit.'
    c = f'''/* {preamble} */
#ifndef LAUBERHORN_ECI_ADDRESS_MAP_H
#define LAUBERHORN_ECI_ADDRESS_MAP_H
/* The includer supplies uint64_t (kernel: the shared inttypes.h).
 * PA lifetime codes are not scheduler slots, task IDs or CPU numbers.
 * These helpers do not authorize access or allocate/recycle lifetime codes. */
'''
    c += ''.join(f'#define LH_MAP_{k.upper()} {v}U\n' for k, v in constants.items())
    c += 'static const uint64_t lh_map_worker_bases[LH_MAP_MAX_WORKERS] = {\n    '
    c += ', '.join(f'0x{v:x}ULL' for v in bases) + '\n};\n'
    c += '''/* Invalid arguments leave *address unchanged. */
static inline int lh_map_encode(unsigned int workers, unsigned int worker,
                                unsigned int domain, unsigned int offset,
                                uint64_t *address)
{
    uint64_t value;
    if (!address || !workers || workers > LH_MAP_MAX_WORKERS ||
        worker >= workers || domain >= LH_MAP_DOMAIN_LIMIT ||
        offset >= LH_MAP_BLOCK_BYTES)
        return -1;
    value = lh_map_worker_bases[worker] | offset;
'''
    c += ''.join(f'    if (domain & (1U << {i})) value ^= 0x{v:x}ULL;\n' for i, v in enumerate(basis))
    c += '''    *address = value;
    return 0;
}
/* Decode arithmetic only. The caller must validate the installed owner and
 * allocation lifetime separately, and preserve accepted addresses to completion.
 * Bypass is deliberately outside the worker namespace. */
static inline int lh_map_decode(unsigned int workers, uint64_t address,
                                unsigned int *worker, unsigned int *domain,
                                unsigned int *offset)
{
    unsigned int code = 0, i;
    uint64_t base = address & ~(uint64_t)(LH_MAP_BLOCK_BYTES - 1U);
    if (!worker || !domain || !offset || !workers || workers > LH_MAP_MAX_WORKERS ||
        address >> LH_MAP_ADDRESS_BITS)
        return -1;
'''
    c += ''.join(f'    code |= ((address >> {p}) & 1ULL) << {i};\n' for i, p in enumerate(pivots))
    c += ''.join(f'    if (code & (1U << {i})) base ^= 0x{v:x}ULL;\n' for i, v in enumerate(basis))
    c += '''    for (i = 0; i < workers; ++i) {
        if (base == lh_map_worker_bases[i]) {
            *worker = i;
            *domain = code;
            *offset = address & (LH_MAP_BLOCK_BYTES - 1U);
            return 0;
        }
    }
    return -1;
}
#endif
'''
    scala = f'''// {preamble}
package lauberhorn.host.eci

/** Arithmetic only: ownership and accepted-transaction lifetime are separate. */
object EciAddressMap {{
'''
    scala += ''.join(f'  val {k}: Int = {v}\n' for k, v in constants.items())
    scala += '  val workerBases: Vector[BigInt] = Vector(' + ', '.join(f'BigInt("{v:x}", 16)' for v in bases) + ')\n'
    scala += '  val domainBasis: Vector[BigInt] = Vector(' + ', '.join(f'BigInt("{v:x}", 16)' for v in basis) + ')\n'
    scala += '  val domainPivots: Vector[Int] = Vector(' + ', '.join(map(str, pivots)) + ')\n'
    scala += '''  def encode(workers: Int, worker: Int, domain: Int, offset: Int = 0): BigInt = {
    require(workers >= 1 && workers <= max_workers)
    require(worker >= 0 && worker < workers)
    require(domain >= 0 && domain < domain_limit)
    require(offset >= 0 && offset < block_bytes)
    domainBasis.zipWithIndex.foldLeft(workerBases(worker) | BigInt(offset)) {
      case (address, (vector, bit)) => if ((domain & (1 << bit)) != 0) address ^ vector else address
    }
  }
  def decode(workers: Int, address: BigInt): Option[(Int, Int, Int)] = {
    if (workers < 1 || workers > max_workers || address < 0 || address >= (BigInt(1) << address_bits))
      return None
    val code = domainPivots.zipWithIndex.foldLeft(0) {
      case (value, (pivot, bit)) => if (address.testBit(pivot)) value | (1 << bit) else value
    }
    val base = domainBasis.zipWithIndex.foldLeft(address & ~BigInt(block_bytes - 1)) {
      case (value, (vector, bit)) => if ((code & (1 << bit)) != 0) value ^ vector else value
    }
    val worker = workerBases.take(workers).indexOf(base)
    if (worker < 0) None else Some((worker, code, (address & BigInt(block_bytes - 1)).toInt))
  }
}
'''
    return {'sw/include/eci_address_map.h': c,
            'hw/src/lauberhorn/host/eci/EciAddressMap.scala': scala}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    for name, content in render().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'stale generated collateral: {name}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
