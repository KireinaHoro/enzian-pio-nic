#!/usr/bin/env python3
"""Generate the small Goal 2 address universe from the selected Goal 1 map."""
import json
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools/progress'))
from capacity import encode, color

def render():
    c = json.loads((ROOT / 'model/steady/selected-8k.json').read_text())[0]['configuration']
    controls, colors, domains = [], {}, {}
    for domain in range(4):
        workers = []
        for worker in range(3):
            base = encode(c, worker, domain)
            directions = []
            for direction in ('rx', 'tx'):
                lines = [base + off for off in c['directions'][direction]['control_offsets_bytes']]
                directions.append('<<' + ', '.join(map(str, lines)) + '>>')
                for addr in lines:
                    colors[addr] = color(addr, c['color_bits'])
                    domains[addr] = domain
            workers.append('<<' + ', '.join(directions) + '>>')
        controls.append('<<' + ', '.join(workers) + '>>')
    case = lambda values: 'CASE ' + '\n    [] '.join(f'a = {a} -> {v}' for a, v in values.items())
    return ('------------------------- MODULE SelectedAddresses -------------------------\n'
            'EXTENDS Naturals\n'
            '\\* Generated by tools/scheduling/addresses.py; actual 8 KiB PA controls.\n'
            'ControlTable == <<' + ',\n    '.join(controls) + '>>\n'
            'Addresses == {' + ', '.join(map(str, colors)) + '}\n'
            'ColorOf == [a \\in Addresses |-> ' + case(colors) + ']\n'
            'DomainOf == [a \\in Addresses |-> ' + case(domains) + ']\n'
            '=============================================================================\n')

if __name__ == '__main__':
    target = ROOT / 'model/scheduling/SelectedAddresses.tla'
    if '--check' in sys.argv:
        assert target.read_text() == render(), 'regenerate selected addresses'
        print('Selected Goal 2 addresses match the Goal 1 encoder')
    else:
        target.write_text(render())
